# -*- coding: utf-8 -*-
"""Vendor Muscat Heist's three NEW faces into brand/heist/fonts/.

Archivo and JetBrains Mono are already in brand/fonts/ (ops/vendor-fonts.py),
and Archivo's cut there spans wdth 62..125, which covers the handoff's 66. This
adds what the Vol.10 handoff introduces:

  Fraunces   italic only (the handoff never sets it upright), with the SOFT and
             WONK axes the tokens ask for — a cut without them draws the
             default, sharper italic and nothing reports it
  Manrope    600 / 700 / 800, the UI face
  (Reem Kufi is NOT vendored: the owner removed the Arabic name, 22 Nov 2026.)

Same reasons as the first script: Chromium here does not trust the proxy's CA,
a failed webfont is a silent fallback, and a phone on a court-side connection
should not wait on Google for the title.

    python3 ops/vendor-heist-fonts.py
"""
import json
import os
import re
import subprocess
import urllib.parse

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "brand", "heist", "fonts")
os.makedirs(OUT, exist_ok=True)
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/120.0.0.0 Safari/537.36")
LATIN = ("U+0000-00FF", "U+0100-02BA")


def get(url):
    return subprocess.check_output(["curl", "-sSL", "-A", UA, url], timeout=60)


def faces(css):
    return re.findall(r"(/\*[^*]*\*/\s*)?@font-face\s*\{([^}]*)\}", css)


def vendor(css, prefix, keep):
    out = []
    for comment, body in faces(css):
        rng = re.search(r"unicode-range:\s*([^;]+);", body)
        if keep and (not rng or not rng.group(1).strip().startswith(keep)):
            continue
        url = re.search(r"url\((https://[^)]+)\)", body).group(1)
        style = re.search(r"font-style:\s*(\w+)", body).group(1)
        weight = re.search(r"font-weight:\s*([\d ]+);", body).group(1).strip().replace(" ", "-")
        sub = "latin-ext" if rng and rng.group(1).startswith("U+0100") else ("latin" if rng else "subset")
        name = f"{prefix}-{style}-{weight}-{sub}.woff2"
        data = get(url)
        assert data[:4] == b"wOF2", f"{name}: not a woff2 ({data[:16]!r})"
        open(os.path.join(OUT, name), "wb").write(data)
        out.append("@font-face {" + re.sub(r"url\(https://[^)]+\)", f"url(./{name})", body) + "}")
        print(f"  {name:44s} {len(data)//1024:4d}KB")
    assert out, f"{prefix}: nothing vendored — the subset filter matched no face"
    return out


blocks = []
fr = get("https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght,SOFT,WONK@1,9..144,400..700,0..100,0..1&display=swap").decode()
blocks += [b for k in LATIN for b in vendor(fr, "Fraunces", k)]
mr = get("https://fonts.googleapis.com/css2?family=Manrope:wght@600;700;800&display=swap").decode()
blocks += [b for k in LATIN for b in vendor(mr, "Manrope", k)]
# THE LOGO'S FACES (owner, 25 Nov 2026: match the app to the new logo, "Bold on
# navy"): Bowlby One for the fat block lettering, Kaushan Script for the brush
# script. Both single-weight; Bowlby One has no latin-ext cut on Google.
bo = get("https://fonts.googleapis.com/css2?family=Bowlby+One&display=swap").decode()
blocks += [b for k in LATIN for b in vendor(bo, "BowlbyOne", k)] if "U+0100" in bo else vendor(bo, "BowlbyOne", LATIN[0])
ks = get("https://fonts.googleapis.com/css2?family=Kaushan+Script&display=swap").decode()
blocks += [b for k in LATIN for b in vendor(ks, "KaushanScript", k)] if "U+0100" in ks else vendor(ks, "KaushanScript", LATIN[0])
# THE APP'S SMALL TEXT (owner, 26 Nov 2026, option 2 of four): Barlow for
# sentences and rows, Barlow Semi Condensed for the spaced-caps labels that were
# JetBrains Mono. The headings are Archivo condensed black (brand/fonts/).
ba = get("https://fonts.googleapis.com/css2?family=Barlow:wght@500;600;700;800&display=swap").decode()
blocks += [b for k in LATIN for b in vendor(ba, "Barlow", k)]
bs = get("https://fonts.googleapis.com/css2?family=Barlow+Semi+Condensed:wght@600;700&display=swap").decode()
blocks += [b for k in LATIN for b in vendor(bs, "BarlowSemiCondensed", k)]
head = ("/* Generated by ops/vendor-heist-fonts.py — do not edit.\n"
        "   Fraunces (italic), Manrope, Bowlby One, Kaushan Script, Barlow, Barlow Semi Condensed;\n"
        "   SIL Open Font License 1.1. */\n")
open(os.path.join(OUT, "fonts.css"), "w").write(head + "\n".join(blocks) + "\n")
print(f"wrote {os.path.relpath(OUT)}/fonts.css  ({len(blocks)} faces)")
